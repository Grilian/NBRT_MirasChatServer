import { fileURLToPath, URL } from 'node:url';
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

// Сборка одного и того же клиента под три цели: веб (раздаётся nginx из
// /miraschat/), десктоп (Electron грузит с диска через file://) и Android
// (Capacitor кладёт файлы в assets и открывает их так же локально).
//
// base: './' — общий знаменатель для всех трёх. Абсолютные пути (`/assets/…`)
// в file:// указывали бы в корень диска, а на вебе приложение живёт не в корне
// домена, а в подпапке. Относительные работают везде, и это безопасно ровно
// потому, что маршрутизации по путям у приложения нет: единственный «адрес»
// внутри — хеш `#superadmin`.
//
// Каталог сборки задаётся снаружи (BUILD_PATH): desktop и mobile собирают в
// свои build-desktop/build-mobile, чтобы не затирать веб-сборку, из которой
// идёт выкладка.
export default defineConfig({
  plugins: [react()],
  base: './',
  // `@` — корень исходников. Импорт между фичами пишется от корня
  // (`@/shared/lib/time`), а не лесенкой `../../../`: путь тогда не зависит от
  // того, на какой глубине лежит импортирующий файл, и переезд каталога не
  // ломает половину импортов в проекте. Внутри своей папки остаётся `./`.
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  build: {
    outDir: process.env.BUILD_PATH || 'build',
    emptyOutDir: true,
    sourcemap: false,
    // Отчёт CRA о размере всегда был «после gzip», и это вводило в
    // заблуждение вдвое. Здесь честный предупредительный порог по сырому
    // размеру: главный кусок больше 700 КБ — повод разбить, а не привыкнуть.
    chunkSizeWarningLimit: 700,
  },
  // host: '127.0.0.1' задан явно. По умолчанию Vite слушает `localhost`, и на
  // Windows это резолвится в IPv6-петлю — сокет открывается только на [::1],
  // куда не достучаться ни curl, ни браузерной панели проверки. CRA слушал
  // IPv4, поэтому расхождение всплыло ровно при переезде.
  server: {
    host: '127.0.0.1',
    port: 3000,
    strictPort: true,
  },
  preview: {
    host: '127.0.0.1',
    port: 3000,
    strictPort: true,
  },
  test: {
    globals: true,
    environment: 'jsdom',
    setupFiles: ['./src/setupTests.ts'],
    css: false,
    // Отдельные окружения на файл: тесты активно подменяют модули и глобальные
    // объекты (клавиатура, matchMedia, платформа), и общий контекст протекал бы
    // между ними.
    isolate: true,
    include: ['src/**/*.{test,spec}.{ts,tsx}'],
  },
});
