import { isNativeMobile } from './mobileNotify';

// Автофокус в поле при ОТКРЫТИИ окна: на ПК он экономит клик, на телефоне —
// мгновенно выдвигает экранную клавиатуру, а она занимает пол-экрана и
// закрывает то самое окно, которое человек только что открыл (в списках
// «Люди»/«Куда переслать» под ней пропадает вся выдача).
//
// Только для полей, которые получают фокус сами. Поля, куда человек зашёл
// осознанно (правка названия группы, заметки о человеке), фокусируются
// по-прежнему всегда — там клавиатура и нужна.
export const AUTOFOCUS_ON_OPEN = !isNativeMobile
  && !window.matchMedia('(pointer: coarse)').matches;
