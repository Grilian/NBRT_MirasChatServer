/**
 * Человеческая расшифровка отказа сервера.
 *
 * Сервер на непредвиденном падении отдаёт `e.message` — это текст исключения
 * SQLite или Node, и обычному человеку он не говорит ничего («SQLITE_CONSTRAINT:
 * FOREIGN KEY constraint failed»). Показывать такое в окне задачи бессмысленно:
 * из него не следует ни что произошло, ни что делать дальше.
 *
 * Поэтому берём текст сервера, только если он написан для людей, а иначе
 * объясняем по коду ответа. Признак простой: осмысленные сообщения у нас
 * по-русски, а исключения приходят латиницей с двоеточиями и подчёркиваниями.
 */
export function describeTaskError(err: any, fallback = 'Не удалось сохранить задачу'): string {
  const fromServer = err?.response?.data?.error;
  if (typeof fromServer === 'string' && /[а-яё]/i.test(fromServer)) return fromServer;

  // Ответа нет вовсе — запрос не доехал.
  if (err?.response === undefined) {
    return 'Нет связи с сервером — задача не сохранена. Проверьте подключение и попробуйте ещё раз.';
  }

  switch (err.response.status) {
    case 400:
      return 'Сервер не принял данные. Проверьте название и срок.';
    case 401:
      return 'Сеанс больше не действителен — войдите заново.';
    case 403:
      return 'Недостаточно прав: править задачу может тот, кто её поставил.';
    case 404:
      return 'Задача не найдена — возможно, её удалили, пока окно было открыто.';
    case 413:
      return 'Слишком длинный текст — сократите описание.';
    default:
      return `${fallback}. Попробуйте ещё раз; если повторится — сообщите администратору.`;
  }
}
