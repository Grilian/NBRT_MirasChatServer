import { TaskItem } from './types';

/**
 * Что считается «моей работой».
 *
 * Правило живёт отдельно, потому что ответ нужен в двух местах: доска в
 * разделе «Задачи» и число на «Главной». Пока их было два, они разошлись —
 * «Главная» считала все активные задачи подряд и показывала «1 задача в
 * работе» там, где вкладка «Моя работа» была пуста: задачу человек завёл сам и
 * никому не назначил, поэтому в его работу она не попадала. Одно правило —
 * расходиться больше нечему.
 *
 * Ничья задача, заведённая кем-то другим, СЧИТАЕТСЯ моей: её никто не делает,
 * а я вправе её взять — именно такие и теряются. Своя же ничья задача моей
 * работой не становится: я её поставил, она видна во вкладке «Поставленные».
 */
export function isMyWork(task: Pick<TaskItem, 'assignee' | 'created_by'>, userId: number): boolean {
  if (task.assignee) return task.assignee.id === userId;
  return task.created_by.id !== userId;
}

/** Охват «Все, к чему причастен»: всё, кроме поставленного мной другим. */
export function isInvolved(task: Pick<TaskItem, 'assignee' | 'created_by'>, userId: number): boolean {
  return task.created_by.id !== userId || task.assignee?.id === userId;
}
