import { readFileSync } from 'node:fs';
import { join } from 'node:path';

// Где имя чата обрезается, а где — нет. Это не вкусовщина, а два разных
// вопроса, и ответы у них противоположные:
//
//   • СТРОКА СПИСКА обрезается. Список сканируют глазом сверху вниз, и
//     возможность это делать даёт одинаковая высота строк; имена в две строки
//     заставляли бы перечитывать список целиком. Начало названия строки
//     различает, полное имя даёт подсказка по наведению.
//   • ШАПКА ПЕРЕПИСКИ не обрезается. Это единственное место, где человек
//     убеждается, в каком он чате, и на телефоне подсказки по наведению нет
//     вовсе: «Методический совет по краеведе…» там не отличить от другого
//     совета.
//
// Проверяется чтением CSS: в jsdom стилей нет вовсе, и `getComputedStyle`
// вернул бы умолчания независимо от файла — такая проверка зеленела бы и на
// сломанной вёрстке. Тот же приём, что у контраста по tokens.css.

const CSS = readFileSync(
  join(__dirname, '..', '..', 'shared', 'styles', 'chat-layout.css'),
  'utf8',
);

function ruleBody(selector: string): string {
  const at = CSS.indexOf(`${selector} {`);
  if (at < 0) throw new Error(`Нет правила ${selector} — селектор переименовали?`);
  return CSS.slice(at, CSS.indexOf('}', at));
}

test('имя чата в ШАПКЕ переносится, а не обрезается', () => {
  const body = ruleBody('.conv-title .name');
  expect(body).not.toContain('text-overflow: ellipsis');
  expect(body).not.toContain('white-space: nowrap');
  // Длинное название без пробелов тоже обязано переноситься, иначе оно просто
  // вылезет за край вместо многоточия.
  expect(body).toContain('overflow-wrap: anywhere');
});

test('имя чата в СТРОКЕ СПИСКА обрезается — и это осознанно', () => {
  // Обратная проверка: если однажды кто-то «починит» строку списка по тому же
  // правилу, что шапку, список начнёт прыгать высотой строк. Тест обязан
  // упасть и заставить прочитать, почему здесь иначе.
  const body = ruleBody('.row-name');
  expect(body).toContain('text-overflow: ellipsis');
  expect(body).toContain('white-space: nowrap');
});
