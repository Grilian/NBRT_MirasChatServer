import { ROSTER_MAX_WIDTH, ROSTER_MIN_WIDTH } from '@/features/settings/uiPrefs';

// Единая адаптивная раскладка приложения: STANDARD → COMPACT → MOBILE.
//
// Главный принцип: размер окна меняет СПОСОБ ПРЕДСТАВЛЕНИЯ приложения, а не
// создаёт другую его версию. Поэтому режим — это одно вычисляемое значение на
// всё приложение, а не набор независимых медиазапросов по месту: раньше список
// чатов переключался по одному порогу, панель ветки по другому, и между ними
// существовали состояния, которых никто не проектировал (например, ветка,
// наехавшая на переписку поверх неё).
//
// Переход происходит не по «красивому» разрешению, а тогда, когда текущий
// набор областей перестаёт помещаться со своими минимальными рабочими
// ширинами. Поэтому расчёт принимает фактическую ширину списка чатов: у того,
// кто растянул список до 500px, переход наступит раньше — и это правильно, он
// сам распорядился местом.
//
// ЧЕТВЁРТОЙ ОБЛАСТИ БОЛЬШЕ НЕТ. До редизайна ветка, сведения о чате и профиль
// жили в собственной колонке справа, и вокруг неё была построена целая
// механика: намерение против возможности (`rightPanelRequested` /
// `rightPanelOpen`), автозакрытие при сужении с возвратом при расширении,
// своя ширина с перетаскиванием, расширение окна Electron под неё. Всё это
// снято: ветка теперь ВРЕМЕННО ЗАМЕНЯЕТ переписку с явным возвратом, а
// сведения и профиль ушли в модальный слой. Режим FULL исчез вместе с
// колонкой — на любой десктопной ширине областей ровно три.

/** Ширины областей, px. Подобраны замером реальной вёрстки, а не «на глаз». */
export const LAYOUT_SIZES = {
  /** Рельс разделов в иконках, см. .chat-layout в chat-layout.css. */
  navRail: 68,
  /**
   * Рельс с подписями — как в концепции редизайна.
   *
   * 210px — это не «покрасивее», а ширина, при которой самое длинное название
   * раздела («Пространства», 12 знаков) помещается целиком рядом с иконкой и
   * счётчиком. Обрезать подписи многоточием здесь нельзя: правило концепции
   * прямо запрещает это для важного текста, а название раздела — ровно оно.
   */
  navRailWide: 210,
  /** Пределы полного списка чатов — те же, что у ручного изменения ширины. */
  rosterMin: ROSTER_MIN_WIDTH,
  rosterMax: ROSTER_MAX_WIDTH,
  /** Компактный список: аватар 40px + поля. Индикаторы влезают, подписи нет. */
  rosterCompact: 68,
  /**
   * Минимум переписки.
   *
   * Число не произвольное и не «поудобнее»: пузырь ограничен 70% ширины, и при
   * 520px это ~364px, то есть 45–50 знаков в строке — нижняя граница удобного
   * чтения. Заодно это ровно то значение, при котором у COMPACT появляется
   * собственная полоса: полный список перестаёт помещаться на 852px, а
   * мобильный режим начинается только с 760px. Возьми меньше 428 — и режим
   * «рельс + иконки + переписка» стал бы недостижим сужением окна, потому что
   * приложение проскакивало бы сразу в мобильный.
   */
  chatMin: 520,
} as const;

/**
 * Порог мобильного режима. Обязан совпадать с `@media (max-width: 760px)` в
 * responsive.css: ниже него всё оформление (нижняя навигация вместо рельса,
 * полноэкранная ветка, свои отступы) уже описано там, и вторая точка
 * переключения рядом означала бы состояние, где половина стилей мобильная, а
 * половина ещё десктопная.
 */
export const MOBILE_MAX_WIDTH = 760;

export type LayoutMode = 'standard' | 'compact' | 'mobile';

export interface LayoutInput {
  /** Ширина окна (viewport). */
  width: number;
  /** Ширина полного списка чатов, выбранная пользователем. */
  rosterWidth: number;
  /**
   * Пользователь САМ свернул список в иконки. `null` — не высказывался, и
   * тогда состоянием распоряжается адаптив.
   */
  rosterCollapsedByUser: boolean | null;
}

export interface LayoutState {
  mode: LayoutMode;
  /** Список чатов показывает только аватары. */
  rosterCompact: boolean;
  /**
   * Рельс разделов показывает подписи рядом с иконками.
   *
   * Ось СВОЯ, отдельная от `mode`: режим описывает список чатов, а рельс
   * уступает место раньше него и по своему условию. Свести их в один
   * четвёртый режим значило бы получить состояние «человек сам свернул
   * список, но места вагон» — и не суметь ответить, широкий это режим или
   * компактный.
   */
  railExpanded: boolean;
  /** Фактическая ширина рельса, px. */
  railWidth: number;
  /** Фактическая ширина списка после ограничений, px. */
  rosterWidth: number;
  /** Сколько остаётся переписке — для отладки и проверок. */
  chatWidth: number;
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

/** Помещается ли набор областей со своими минимумами. */
function fits(width: number, parts: number[]): boolean {
  return parts.reduce((sum, part) => sum + part, 0) <= width;
}

/**
 * Единственное место, где решается, как выглядит приложение при данной ширине.
 *
 * Порядок уступок задан требованиями и менять его нельзя: сначала рельс
 * разделов теряет подписи и сжимается в иконки, затем список чатов сжимается в
 * иконки, и только потом — мобильный режим. Переписка не ужимается ниже своего
 * минимума ни на одном шаге: ради этого всё и делается.
 *
 * Почему подписи уступают ПЕРВЫМИ: раздел и без подписи опознаётся по иконке и
 * по подсказке, а список чатов без имён и превью не опознаётся никак. Отдавать
 * ради подписей место переписке или списку значит платить содержимым за
 * оформление.
 */
export function resolveLayout(input: LayoutInput): LayoutState {
  const { navRail, navRailWide, rosterMin, rosterMax, rosterCompact, chatMin } = LAYOUT_SIZES;
  const width = Math.max(0, input.width);

  const mobile = (): LayoutState => ({
    // В мобильном режиме ширины областей не участвуют в раскладке вовсе:
    // экран занимает ровно один экран приложения. Рельс там — нижняя панель,
    // подписи в ней есть всегда и от ширины не зависят.
    mode: 'mobile',
    rosterCompact: false,
    railExpanded: false,
    railWidth: 0,
    rosterWidth: input.rosterWidth,
    chatWidth: width,
  });

  if (width <= MOBILE_MAX_WIDTH) return mobile();

  const desiredRoster = clamp(input.rosterWidth, rosterMin, rosterMax);

  // Список в иконках — либо по воле человека, либо потому, что полный уже не
  // оставляет переписке её минимума. Явное «разверни» уважается ровно до тех
  // пор, пока полный список вообще помещается: иначе пришлось бы ужимать
  // переписку, а это запрещено.
  const fullRosterFits = fits(width, [navRail, rosterMin, chatMin]);
  const compact = input.rosterCollapsedByUser === true || !fullRosterFits;

  // Даже минимальный десктоп не собирается — промежуточных режимов здесь не
  // предусмотрено, сразу мобильный.
  if (!fits(width, [navRail, rosterCompact, chatMin])) return mobile();

  // Подписи на рельсе — если широкий рельс помещается рядом с ПОЛНЫМ списком.
  //
  // Считать здесь по фактической ширине списка нельзя, и это не мелочь:
  // свёрнутый АДАПТИВОМ список освободил место не потому, что оно лишнее, а
  // потому, что его не хватало, — и рельс, забравший это место под подписи,
  // получил бы 210px оформления рядом с чатами, от которых остались одни
  // аватары. Ровно обратный порядок уступок. Поймано тестом на монотонность:
  // на 798px подписи возвращались сами.
  //
  // Свёрнутый ЧЕЛОВЕКОМ список — другое дело: он распорядился местом сам, и
  // рельс вправе его занять.
  const collapsedByUser = input.rosterCollapsedByUser === true;
  const railExpanded = fits(width, [navRailWide, collapsedByUser ? rosterCompact : rosterMin, chatMin]);
  const railWidth = railExpanded ? navRailWide : navRail;

  // Переписке достаётся всё, что осталось, но не меньше её минимума: при
  // нехватке места сужается не она, а сам список (в пределах своего минимума).
  const rosterActual = compact
    ? rosterCompact
    : clamp(width - railWidth - chatMin, rosterMin, desiredRoster);

  return {
    mode: compact ? 'compact' : 'standard',
    rosterCompact: compact,
    railExpanded,
    railWidth,
    rosterWidth: rosterActual,
    chatWidth: width - railWidth - rosterActual,
  };
}
