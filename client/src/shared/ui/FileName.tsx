import React from 'react';
import { splitFileName } from '@/shared/lib/fileName';

/**
 * Имя файла, которое обрезается ПОСЕРЕДИНЕ, а не с конца.
 *
 * Обычная обрезка срезает расширение — то есть ровно ту часть, которая
 * отвечает на вопрос «что это за файл»: «Расписание мероприятий на сентябрь
 * 2026 года.docx» превращалось в «Расписание мероприятий н…». Начало у длинных
 * имён часто общее, различает их как раз хвост.
 *
 * Отдельным компонентом, а не тремя копиями по месту: имя файла показывается в
 * разделе «Файлы», во вложениях чата и в карточке файла внутри сообщения, и
 * три копии разъехались бы на первой же правке — как уже расходились правила
 * видимости календаря и регэксп кодов смайликов.
 *
 * Сжимает CSS: голова получает `text-overflow`, хвост стоит `flex: none`.
 * Ничего не мерим и не пересчитываем при изменении ширины.
 */
const FileName: React.FC<{ name: string | null | undefined; className?: string }> = ({
  name, className = '',
}) => {
  const value = name || 'Файл';
  const { head, tail } = splitFileName(value);

  return (
    // title — чтобы полное имя дочитывалось наведением, даже когда серединой
    // пожертвовали: на очень узком экране голова сжимается до пары букв.
    <span className={'file-name ' + className} title={value}>
      <span className="file-name-head">{head}</span>
      {tail && <span className="file-name-tail">{tail}</span>}
    </span>
  );
};

export default FileName;
