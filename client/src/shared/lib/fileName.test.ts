import { splitFileName } from './fileName';

test('расширение отделяется и показывается всегда', () => {
  // Именно оно отвечает на вопрос «что это за файл», и именно оно срезалось
  // при обрезке с конца.
  expect(splitFileName('Расписание мероприятий на сентябрь 2026 года.docx'))
    .toEqual({ head: 'Расписание мероприятий на сентябрь 2026 года', tail: '.docx' });
});

test('составное расширение отдаёт последнюю часть', () => {
  expect(splitFileName('backup.tar.gz')).toEqual({ head: 'backup.tar', tail: '.gz' });
});

test('имя без точки остаётся целым', () => {
  expect(splitFileName('Договор')).toEqual({ head: 'Договор', tail: '' });
});

test('скрытый файл — не «расширение на всё имя»', () => {
  // Точка в начале: отрезав по ней, мы оставили бы пустое начало и всё имя в
  // хвосте, который не сжимается, — строка перестала бы помещаться вовсе.
  expect(splitFileName('.gitignore')).toEqual({ head: '.gitignore', tail: '' });
});

test('точка на конце расширением не считается', () => {
  expect(splitFileName('Черновик.')).toEqual({ head: 'Черновик.', tail: '' });
});

test('длинный хвост — это не расширение, а имя с точкой', () => {
  // «Отчёт за 2026.финальная версия»: закрепить за таким хвостом место значит
  // отдать ему пол-строки и сжать то, что человек читает первым.
  expect(splitFileName('Отчёт за 2026.финальная версия'))
    .toEqual({ head: 'Отчёт за 2026.финальная версия', tail: '' });
});

test('обычные картинки и документы разбираются как ожидается', () => {
  expect(splitFileName('IMG_20260903_124233.jpg').tail).toBe('.jpg');
  expect(splitFileName('Афиша ко Дню солидарности.png').tail).toBe('.png');
  expect(splitFileName('SipLip_Stations_Log_Investigation_2026.xlsx').tail).toBe('.xlsx');
});
