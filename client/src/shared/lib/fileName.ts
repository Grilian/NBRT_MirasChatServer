/**
 * Разбор имени файла на «начало» и «хвост с расширением».
 *
 * Зачем. Имя файла обрезалось с конца — как обычный текст: «Расписание
 * мероприятий на сентябрь 2026 года.docx» превращалось в «Расписание
 * мероприятий н…». Срезалось при этом РАСШИРЕНИЕ, то есть ровно та часть,
 * которая отвечает на вопрос «что это за файл»: документ, картинка или
 * установщик. Начало у длинных имён часто общее («Расписание мероприятий
 * на…»), и различает их как раз хвост.
 *
 * Поэтому обрезка идёт посередине: начало сжимается многоточием, а хвост
 * показывается всегда. Само сжатие делает CSS (`text-overflow` на первой
 * части), здесь только раскладка строки — так не нужно ничего мерить и
 * пересчитывать при изменении ширины.
 */

/**
 * Хвост длиннее этого расширением не считается.
 *
 * «Отчёт за 2026.финальная версия» — не файл с расширением «финальная
 * версия», а имя с точкой посередине; закреплять за таким хвостом место
 * значило бы отдать ему пол-строки.
 */
const MAX_EXTENSION = 10;

export interface SplitName {
  /** Сжимается многоточием, когда не помещается. */
  head: string;
  /** Показывается всегда. Пусто, если расширения нет. */
  tail: string;
}

export function splitFileName(name: string): SplitName {
  const dot = name.lastIndexOf('.');
  // Точка в самом начале — это не расширение, а скрытый файл («.gitignore»):
  // отрезав тут, мы оставили бы пустое начало и всё имя в хвосте.
  if (dot <= 0 || dot === name.length - 1) return { head: name, tail: '' };

  const tail = name.slice(dot);
  if (tail.length > MAX_EXTENSION) return { head: name, tail: '' };
  return { head: name.slice(0, dot), tail };
}
