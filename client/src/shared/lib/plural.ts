/**
 * Русское склонение по числу: «1 задача / 2 задачи / 5 задач».
 *
 * Одна функция на приложение. До этого правило было переписано четырьмя
 * разными способами в четырёх файлах — где-то через `mod100 >= 11 && <= 14`,
 * где-то через `mod100 !== 11`, — и проверить их разом было негде. Форма 11–14
 * («11 задач», не «11 задача») ошибается чаще всего именно потому, что каждый
 * раз пишется заново.
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 14) return many;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}
