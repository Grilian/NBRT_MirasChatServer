// Хвост оборванного кода в конце строки.
//
// Обрезка сообщения по длине не должна оставлять огрызок вида `:e~1f6`:
// картинкой он уже не станет, а в базе останется навсегда.
//
// В тексте бывает РОВНО ОДИН вид кода — выбор оформления `:e~<ключ>~<пак>:`
// (см. client/src/utils/customEmoji.ts). Прежние `:name:` сняты 07.09.2026
// вместе с картиночными смайликами, и вместе с ними ушла причина, по которой
// этот шаблон трижды разъезжался между клиентом и сервером: раньше он должен
// был ловить произвольное имя, а теперь — конкретную известную форму.
//
// Побочно исчезла известная неточность: «встреча в 10:30» больше не теряет
// хвост, потому что `:30` не начинается с `e~`.
//
// Клиентская пара — `trimDanglingShortcode` в `client/src/utils/customEmoji.ts`.
// Языки разные, общий модуль не сделать, поэтому при правке одного значения
// второе обязано меняться вместе с ним.
const DANGLING_SHORTCODE = /:e~[a-z0-9_~-]{0,126}$/;

/** Строка без незакрытого кода на конце. */
const trimDanglingShortcode = (text) => String(text ?? '').replace(DANGLING_SHORTCODE, '');

module.exports = { DANGLING_SHORTCODE, trimDanglingShortcode };
