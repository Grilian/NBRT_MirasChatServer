// Хвост оборванного кода смайлика в конце строки.
//
// Обрезка сообщения по длине не должна оставлять огрызок вида `:cat` или
// `:e~1f6`: картинкой он уже не станет, а в базе останется навсегда. Шаблон
// живёт ОДНИМ определением, потому что разъехавшиеся копии этого правила и
// были причиной бага: с появлением кода выбора оформления
// `:e~<ключ>~<пак>:` (1.11.14) клиент расширил класс символов до `~` и длину
// до 128, а серверная обрезка осталась на прежнем `[a-z0-9_]{1,32}` — и такой
// код резала посередине.
//
// Клиентская пара — `trimDanglingShortcode` в `client/src/utils/customEmoji.ts`.
// Языки разные, общий модуль не сделать, поэтому при правке одного значения
// второе обязано меняться вместе с ним.
const DANGLING_SHORTCODE = /:[a-z0-9_~-]{1,128}$/;

/** Строка без незакрытого кода на конце. */
const trimDanglingShortcode = (text) => String(text ?? '').replace(DANGLING_SHORTCODE, '');

module.exports = { DANGLING_SHORTCODE, trimDanglingShortcode };
