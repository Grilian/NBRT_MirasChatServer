/**
 * Отзыв сеансов: эпоха токена.
 *
 * Токены выдаются БЕЗ срока (решение старое: людям неудобно логиниться заново
 * каждую неделю), и до сих пор отозвать их было нечем. Отсюда дыра, найденная
 * пользователем 09.09.2026: человек меняет или сбрасывает пароль на одном
 * устройстве, а второе продолжает работать как ни в чём не бывало — то есть
 * смена пароля не выгоняет того, кто пароль подсмотрел.
 *
 * Механика самая простая из работающих: у каждого человека номер эпохи. Он
 * попадает в токен при выдаче и сверяется при каждой проверке. Сменить пароль
 * или нажать «Выйти на других устройствах» — значит увеличить номер: все
 * выданные раньше токены разом перестают подходить, а устройству, с которого
 * действие сделано, тут же выдаётся новый.
 *
 * Отдельной таблицы сеансов не заводим: она отвечала бы на вопрос «какие
 * устройства сейчас в сети», а спрошено было другое — «как выгнать всех
 * остальных». Таблица потребовала бы чистки, и хранила бы то, чем никто не
 * пользуется.
 */
module.exports = function migrateSessions(db) {
  try {
    db.exec('ALTER TABLE users ADD COLUMN token_epoch INTEGER NOT NULL DEFAULT 1');
  } catch (e) {
    // Колонка уже есть — шаг выполняется на каждом старте и обязан это переживать.
  }

  // Уже выданные токены эпохи не содержат вовсе. Считать их недействительными
  // значило бы разлогинить разом всю организацию на ровном месте, поэтому
  // проверка построена так: нет эпохи в токене — сверяем с первой (см.
  // middleware/verifyToken.js). Первый же отзыв поднимет номер и отсечёт их.
  db.exec('UPDATE users SET token_epoch = 1 WHERE token_epoch IS NULL OR token_epoch < 1');
};
