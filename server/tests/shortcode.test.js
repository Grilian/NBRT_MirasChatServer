const assert = require('node:assert/strict');
const test = require('node:test');
const { trimDanglingShortcode } = require('../utils/shortcode');

// Обрезка сообщения по MAX_MESSAGE_LENGTH не должна оставлять в базе огрызок
// кода: картинкой он уже не станет, а лежать там будет вечно.
test('оборванный код смайлика срезается с конца строки', () => {
  assert.equal(trimDanglingShortcode('привет :cat'), 'привет ');
  assert.equal(trimDanglingShortcode('текст :u_1f600'), 'текст ');
});

test('код выбора оформления тоже срезается — он несёт ~ и длиннее 32 знаков', () => {
  // Ровно та регрессия, из-за которой шаблон и сводился в одно место: клиент
  // с 1.11.14 кладёт в текст `:e~<unicode_key>~<packKey>:`, а серверная
  // обрезка знала только про `[a-z0-9_]{1,32}` и резала такой код посередине.
  assert.equal(trimDanglingShortcode('смотри :e~1f469-200d-1f4bb~google-fonts'), 'смотри ');
  assert.equal(trimDanglingShortcode('край :e~1f6'), 'край ');
});

test('целый код и обычный текст не трогаются', () => {
  // Закрывающее двоеточие есть — код целый, резать нечего.
  assert.equal(trimDanglingShortcode('привет :cat:'), 'привет :cat:');
  assert.equal(trimDanglingShortcode('обычный текст'), 'обычный текст');
  // Одинокое двоеточие в конце остаётся: квантификатор {1,…}, а не {0,…} —
  // с нулём шаблон съедал бы закрывающее двоеточие только что вставленного
  // целого кода, и смайлик молча не отправлялся.
  assert.equal(trimDanglingShortcode('вот:'), 'вот:');
});

test('известная неточность: хвост после двоеточия срезается и когда это не код', () => {
  // «10:30» в КОНЦЕ обрезанной строки неотличимо от начала кода `:30sec:`, и
  // шаблон срезает его. Это поведение было и до сведения шаблона в одно место
  // — правило одинаково на клиенте и на сервере, и расходиться им нельзя.
  // Цена мала: обрезка вообще срабатывает лишь на сообщениях длиннее
  // MAX_MESSAGE_LENGTH, то есть там, где текст и так уже обрублен.
  assert.equal(trimDanglingShortcode('встреча в 10:30'), 'встреча в 10');
});

test('пустое и отсутствующее значение не роняют обрезку', () => {
  assert.equal(trimDanglingShortcode(''), '');
  assert.equal(trimDanglingShortcode(null), '');
  assert.equal(trimDanglingShortcode(undefined), '');
});
